#!/usr/bin/env python3
"""Generate the manuscript's data tables from results/results.json.

Tables are written to paper/generated/ and included by the sections.  Nothing
here is typed by hand; scripts/check_numbers.py fails the build if a committed
table disagrees with the results file.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "results.json"
OUT = ROOT / "paper" / "generated"

HEADER = "% Auto-generated by scripts/gen_tables.py. Do not edit.\n"

#: Display order and LaTeX labels for the model comparison.
MODEL_LABEL = {
    "lcdm": r"$\LCDM$",
    "xi_h": r"$\Gam=\xi\Hub$",
    "reinforce": r"reinforced, $\beta=0$",
    "memory": r"reinforced with memory",
    "track_b": r"with reverse channel",
}
PARAM_LABEL = {
    "omega_b": r"$\omega_{\rm b}$",
    "omega_c": r"$\omega_c$",
    "omega_V_act": r"$\omega_{V,\rm act}$",
    "eps": r"$\epsilon$",
    "log10_gamma0": r"$\log_{10}(\Gamz/H_{100})$",
    "log10_xi": r"$\log_{10}\xi$",
    "alpha_tot": r"$\alpha+\beta$",
    "r_beta": r"$\beta/(\alpha+\beta)$",
    "log10_tau": r"$\log_{10}(\tauM H_{100})$",
    "z_act": r"$\zact$",
    "log10_gamma_down": r"$\log_{10}(\Gamdn/H_{100})$",
}
DERIVED_LABEL = {
    "H0": r"$\Hz$ [\si{\kilo\metre\per\second\per\mega\parsec}]",
    "Omega_m0": r"$\Omega_{\rm m0}$",
    "Omega_V0": r"$\Omega_{V0}$",
    "f0": r"$\fconv_0$",
    "matter_deficit": r"$\Delta$",
    "q0": r"$q_0$",
    "j0": r"$j_0$",
    "z_acc": r"$z_{\rm acc}$",
}


#: Quantities that vanish in the LambdaCDM limit and therefore pile up against
#: their prior boundary.  For these a two-sided interval is misleading and a
#: one-sided 95% upper limit is quoted instead.
ONE_SIDED = {"eps", "f0", "matter_deficit", "V0_minus_Vact"}


def profiled_quantities() -> set[str]:
    """Derived quantities with a profile that actually crosses the threshold.

    A one-sided "95% upper limit" read off a marginal posterior is only a
    limit if the likelihood rises. For a quantity that is a monotone function
    of an unidentified direction it does not: the number is the prior's 95th
    percentile. The text withdraws the limit on the convertible fraction for
    exactly this reason, and the converted fraction today -- a monotone
    function of the same directions -- was still being quoted a page later.

    The criterion is applied rather than argued: a derived quantity is quoted
    as a limit only if ``results/profile.json`` holds a profile for it whose
    Delta chi-square crosses 2.71.
    """
    import json as _json
    path = ROOT / "results" / "profile.json"
    if not path.exists():
        return set()
    out = set()
    for entry in _json.loads(path.read_text()).values():
        q = entry.get("quantity")
        if q and not entry.get("unbounded", True):
            out.add(q)
    return out


#: A parameter whose 5--95 span covers more than this fraction of its prior is
#: not measured; the number that would be printed for it is the prior's, not
#: the data's.  Same threshold and same definition as the chain-stability gate,
#: imported rather than repeated so the table and the gate cannot disagree.
def _prior_fill_max() -> float:
    import importlib.util
    spec = importlib.util.spec_from_file_location(
        "_ccs", ROOT / "scripts" / "check_chain_stability.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return float(mod.PRIOR_FILL_MAX)


def prior_fill(model: str, name: str, entry: dict) -> float | None:
    """Fraction of the prior covered by the 5--95 span, or None if unknown."""
    import sys as _sys
    _sys.path.insert(0, str(ROOT / "code"))
    try:
        from absorb.params import MODELS
        m = MODELS[model]
        priors = dict(zip(m.params, m.priors()))
    except Exception:
        return None
    pr = priors.get(name)
    if pr is None or "hi95" not in entry or "lo95" not in entry:
        return None
    width = pr.high - pr.low
    return None if width <= 0 else (entry["hi95"] - entry["lo95"]) / width


def unconstrained_cell() -> str:
    return r"\emph{unconstrained}"


def upper_limit(samples_entry: dict, fmt: str = ".4f") -> str:
    """95% upper limit, for quantities bounded below by zero."""
    hi = samples_entry.get("hi95")
    if hi is None:
        v, e = samples_entry.get("value", samples_entry.get("median", 0.0)), \
               samples_entry.get("err_hi", 0.0)
        hi = v + 2.0 * e
    return rf"$< {hi:{fmt}}$ (95\%)"


def pm(entry: dict, fmt: str = ".4f") -> str:
    """Median with asymmetric 68% credible interval."""
    if "value" in entry:
        v, lo, hi = entry["value"], entry.get("err_lo", 0), entry.get("err_hi", 0)
    else:
        v = entry["median"]
        lo, hi = v - entry.get("lo68", v), entry.get("hi68", v) - v
    if abs(hi - lo) < 0.05 * max(abs(hi), abs(lo), 1e-30):
        return rf"${v:{fmt}} \pm {0.5*(lo+hi):{fmt}}$"
    return rf"${v:{fmt}}^{{+{hi:{fmt}}}}_{{-{lo:{fmt}}}}$"


def comparison_table(chains: dict) -> str:
    """Evidence relative to LambdaCDM, with chi-square alongside.

    AIC and BIC used to be the headline here and are gone.  At eps = 0 the
    larger models reduce to LambdaCDM identically for *any* value of their rate
    parameters, so those parameters are unidentified under the null: that is
    Davies' problem, the effective parameter count at the null is not the
    sampled count, and both 2k and k ln n penalise a number that does not
    describe the model at the point being tested.  The evidence needs no count.
    A direction along which the likelihood is flat contributes its prior volume
    and nothing more, which is the right accounting for a parameter the data do
    not identify.
    """
    import json as _json
    path = ROOT / "results" / "evidence.json"
    if not path.exists():
        return HEADER + "% results/evidence.json not present yet\n"
    ev = _json.loads(path.read_text())
    ref = ev.get("lcdm__baseline")
    if ref is None:
        return HEADER + "% no LambdaCDM evidence to compare against\n"

    # Chi-square comes from the single maximisation protocol where it exists.
    # Neither of the other two sources is a maximum: a nested sampler's best
    # *sample* is not one, which is why the seven-parameter model briefly
    # appeared to fit worse than the three-parameter model it contains; and the
    # chains were polished under budgets that differed by model.
    mpath = ROOT / "results" / "map.json"
    maps = _json.loads(mpath.read_text()) if mpath.exists() else {}

    def chi2_of(name: str) -> tuple[float, str]:
        key = f"{name}__baseline"
        if key in maps:
            return maps[key]["chi2_min"], "map"
        if key in chains and "chi2_min" in chains[key]:
            return chains[key]["chi2_min"], "chain"
        return ev[key]["chi2_min"], "nested sample"

    rows, sources = [], set()
    c2_ref, src_ref = chi2_of("lcdm")
    sources.add(src_ref)
    for name in MODEL_LABEL:
        e = ev.get(f"{name}__baseline")
        if e is None:
            continue
        lnb = e["logz"] - ref["logz"]
        err = (e["logz_err"] ** 2 + ref["logz_err"] ** 2) ** 0.5
        c2, src = chi2_of(name)
        sources.add(src)
        rows.append((MODEL_LABEL[name], e["ndim"], c2, c2 - c2_ref,
                     e["logz"], e["logz_err"], lnb, err))
    if not rows:
        return HEADER + "% no evidences available yet\n"

    lines = [HEADER, r"\begin{tabular}{lrrrrr}", r"\toprule",
             r"Model & $k$ & $\chisq_{\min}$ & $\Delta\chisq$ "
             r"& $\ln Z$ & $\ln B$ \\", r"\midrule"]
    for label, k, c2, dc2, lnz, lnzerr, lnb, err in rows:
        b = "---" if abs(lnb) < 1e-12 else rf"${lnb:+.2f}\pm{err:.2f}$"
        lines.append(rf"{label} & {k} & {c2:.2f} & {dc2:+.2f} "
                     rf"& ${lnz:.2f}\pm{lnzerr:.2f}$ & {b} \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    if sources - {"map"}:
        lines.append(r"\\[2pt]{\footnotesize Not every $\chisq_{\min}$ comes "
                     r"from the common maximisation protocol; see the text.}")
    return "\n".join(lines) + "\n"


def parameter_table(chains: dict, model: str = "memory") -> str:
    """Posterior for one model, or a visible placeholder saying it is missing.

    It used to emit a bare comment, which LaTeX renders as nothing at all: the
    manuscript carried a numbered table with a caption describing a posterior
    and no posterior under it, and nothing in the build objected. A missing
    input should be loud.
    """
    key = f"{model}__baseline"
    if key not in chains:
        return (HEADER + r"\textbf{[missing: no posterior for model '"
                + model + r"' in results.json]}" + "\n")
    c = chains[key]
    # Three columns, because two hid the thing that matters. The last one is
    # the fraction of the prior the 5--95 span covers, by the same definition
    # the chain-stability gate uses; a reader can then see for every parameter
    # how much of what is printed is the data and how much is the prior.
    lines = [HEADER, r"\begin{tabular}{llr}", r"\toprule",
             r"Parameter & Posterior (median, 68\%) & prior filled \\",
             r"\midrule"]
    fill_max = _prior_fill_max()
    for p, entry in c["parameters"].items():
        # A parameter the data do not constrain gets no number. The text says
        # in as many words that the limit on eps is withdrawn because the
        # optimiser can always send the rate to zero; the table went on
        # printing "< 0.83 (95%)" for it anyway, which is the prior's 95th
        # percentile and contradicts the paragraph beside it.
        fill = prior_fill(model, p, entry)
        if fill is not None and fill > fill_max:
            cell = unconstrained_cell()
        elif p in ONE_SIDED:
            cell = upper_limit(entry)
        else:
            cell = pm(entry)
        frac = "---" if fill is None else rf"{fill:.0%}".replace("%", r"\%")
        lines.append(rf"{PARAM_LABEL.get(p, p)} & {cell} & {frac} \\")
    profiled = profiled_quantities()
    lines.append(r"\midrule")
    lines.append(r"\multicolumn{3}{l}{\emph{derived}}\\")
    for p, label in DERIVED_LABEL.items():
        if p in c.get("derived", {}):
            fmt = ".2f" if p == "H0" else ".4f"
            entry = c["derived"][p]
            if p in ONE_SIDED and p not in profiled:
                cell = r"\emph{prior-limited}"
            elif p in ONE_SIDED:
                cell = upper_limit(entry, fmt)
            else:
                cell = pm(entry, fmt)
            lines.append(rf"{label} & {cell} & \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def dataset_table() -> str:
    rows = [
        ("Type Ia supernovae", "Pantheon+", "1701 light curves, full covariance",
         r"\parencite{brout2022_220204077}"),
        ("Baryon acoustic oscillations", "DESI DR2",
         "13 measurements, $0.30\\le z\\le2.33$",
         r"\parencite{collaboration2025_250314738}"),
        ("Cosmic chronometers", "Moresco compilation",
         "15 measurements of $\\Hub(z)$, full covariance",
         r"\parencite{moresco2022_220107241}"),
        ("Compressed CMB", "Planck 2018 distance priors",
         "$\\shift$, $\\lA$, $\\omega_{\\rm b}$",
         r"\parencite{chen2018_180805724,collaboration2018_180706209}"),
        # Used only in the "+growth" combination of sec:observations, and
        # listed here because a quantitative evidence is quoted from it: a
        # number in the manuscript may not rest on a data set the manuscript
        # does not name.
        ("Redshift-space distortions", "SDSS DR16 (eBOSS)",
         "4 measurements of $\\fsig$, $0.38\\le z\\le1.48$; the "
         "$\\fsig$ sub-block of the consensus covariance",
         r"\parencite{alam2021_eboss}"),
    ]
    lines = [HEADER, r"\begin{tabular}{lL{0.20\textwidth}L{0.32\textwidth}l}",
             r"\toprule", r"Probe & Data set & Content & Reference \\",
             r"\midrule"]
    for probe, name, content, ref in rows:
        lines.append(rf"{probe} & {name} & {content} & {ref} \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    data = json.loads(RESULTS.read_text()) if RESULTS.exists() else {}
    chains = data.get("chains", {})
    (OUT / "tab_datasets.tex").write_text(dataset_table())
    (OUT / "tab_comparison.tex").write_text(comparison_table(chains))
    (OUT / "tab_parameters.tex").write_text(parameter_table(chains))
    print(f"wrote 3 tables to {OUT.relative_to(ROOT)} "
          f"({len(chains)} chain(s) available)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
