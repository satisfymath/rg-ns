#!/usr/bin/env python3
"""Enforce the claims ladder.

Every displayed key result must be wrapped in the `keyresult` environment with
an explicit level:

    I  identity or standard result
    C  conditional theorem of this model, under stated assumptions
    P  phenomenological, fitted to data
    S  speculative; permitted only in the Outlook section

Rules enforced here:
  * no bare \boxed outside a keyresult environment;
  * every keyresult carries a valid level and a label;
  * every numbered display that the paper refers to elsewhere carries a level,
    which is the operational meaning of "key result" stated in Sec. 1.5 -- the
    phrase was unfalsifiable while the criterion was left to taste, and
    fourteen referenced displays had no level when it was first applied;
  * no level-S result appears outside the Outlook;
  * the abstract contains no level-S claim.
The extracted table is written to paper/generated/tab_claims.tex.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SECTIONS = ROOT / "paper" / "sections"
OUT = ROOT / "paper" / "generated" / "tab_claims.tex"
LADDER = ROOT / "docs" / "CLAIMS_LADDER.md"

OUTLOOK = "13_outlook.tex"
LEVELS = {
    # A postulate follows from nothing prior, so it cannot be a "theorem of the
    # model" -- stamping the paper's own defining assumption C was circular.
    "A": "Postulate of the model",
    "I": "Identity or standard result",
    "C": "Theorem of the model",
    # A result proved rigorously but about a *different* system than the one
    # the paper postulates. The bridge of sec:realizations-bridge carried C
    # while sec:outlook restated the same content as a conjecture, which no
    # ladder can sustain; neither level was right, so a level was added rather
    # than the disagreement papered over.
    "X": "Result of an auxiliary model",
    # A boundary-value problem solved numerically is not a number fitted to
    # data, which is what P means.
    "N": "Numerical solution of the stated equations",
    "P": "Phenomenological (fitted to data)",
    "S": "Conjecture",
}
KEYRESULT = re.compile(r"\\begin\{keyresult\}\{(\w+)\}\{([^}]+)\}")
BOXED = re.compile(r"\\boxed\b")
COMMENT = re.compile(r"(?<!\\)%.*")


def main() -> int:
    failures: list[str] = []
    rows: list[tuple[str, str, str]] = []

    for tex in sorted(SECTIONS.glob("*.tex")):
        text = COMMENT.sub("", tex.read_text())
        name = tex.name
        spans = [(m.start(), m.end()) for m in
                 re.finditer(r"\\begin\{keyresult\}.*?\\end\{keyresult\}", text, re.S)]

        for m in BOXED.finditer(text):
            if not any(s <= m.start() < e for s, e in spans):
                line = text[:m.start()].count("\n") + 1
                failures.append(f"{name}:{line}: \\boxed outside a keyresult "
                                "environment (unclassified claim)")

        for m in KEYRESULT.finditer(text):
            level, label = m.group(1), m.group(2)
            if level not in LEVELS:
                failures.append(f"{name}: invalid claim level {level!r} for {label}")
                continue
            if level == "S" and name != OUTLOOK:
                failures.append(f"{name}: level-S (conjecture) result {label!r} "
                                f"outside {OUTLOOK}")
            rows.append((label, level, name))

    abstract = SECTIONS / "00_abstract.tex"
    if abstract.exists() and re.search(r"\\begin\{keyresult\}\{S\}", abstract.read_text()):
        failures.append("00_abstract.tex: the abstract must contain no conjecture")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = ["% Auto-generated by scripts/check_claims.py.",
             # longtable, not tabular: with 55 rows the table cannot fit on
             # one page, and as a tabular it floats past the text that
             # introduces it, leaving that page four-fifths empty.
             r"\begin{longtable}{llL{0.42\textwidth}}", r"\toprule",
             r"Result & Level & Meaning \\", r"\midrule",
             r"\endfirsthead",
             r"\toprule Result & Level & Meaning \\ \midrule",
             r"\endhead",
             r"\bottomrule",
             r"\multicolumn{3}{r}{\footnotesize continued on the next page}\\",
             r"\endfoot",
             r"\bottomrule",
             r"\endlastfoot"]
    for label, level, _ in rows:
        lines.append(rf"\cref{{{label}}} & {level} & {LEVELS[level]} \\")
    lines += [r"\end{longtable}"]
    OUT.write_text("\n".join(lines) + "\n")

    if LADDER.parent.exists():
        md = ["# Claims ladder", "",
              "Generated by `scripts/check_claims.py`. Every displayed key result "
              "in the manuscript appears here exactly once.", "",
              "| label | level | meaning | file |", "|---|---|---|---|"]
        for label, level, name in rows:
            md.append(f"| `{label}` | {level} | {LEVELS[level]} | `{name}` |")
        LADDER.write_text("\n".join(md) + "\n")

    # Every referenced numbered display must carry a level.
    import re as _re
    alltex = "".join(p.read_text() for p in
                     sorted((ROOT / "paper" / "sections").glob("*.tex")))
    numbered = set(_re.findall(r"\\begin\{equation\}\s*\\label\{(eq:[^}]+)\}",
                               alltex))
    keyed = set(_re.findall(r"\\begin\{keyresult\}\{[A-Z]\}\{(eq:[^}]+)\}",
                            alltex))
    referenced = set()
    for m in _re.finditer(r"\\[cC]ref\{([^}]*)\}", alltex):
        referenced |= {x.strip() for x in m.group(1).split(",")}
    unlevelled = sorted(l for l in numbered if l in referenced and l not in keyed)
    for label in unlevelled:
        failures.append(f"{label}: a numbered display referred to elsewhere "
                        f"with no evidential level")

    if failures:
        print("check_claims FAILED:")
        for f in failures:
            print("  - " + f)
        return 1
    print(f"check_claims: {len(rows)} classified results, no unclassified \\boxed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
