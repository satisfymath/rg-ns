#!/usr/bin/env python3
"""Turn results/results.json into LaTeX macros.

No number in the manuscript is typed by hand: every quoted value is a
\newcommand generated here from the JSON that the analysis scripts write.
scripts/check_numbers.py enforces that rule by regenerating this file and
failing if it differs from what is committed.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results" / "results.json"
OUT = ROOT / "paper" / "generated" / "numbers.tex"

#: Every results file the manuscript quotes from, with the prefix its keys are
#: given.  A file that is not listed here cannot reach the paper, which is the
#: point: the caustic subsection was for a while quoting seven hand-invented
#: macro names from ``pancake.json``, a file no script read, one of them for a
#: quantity that had never been computed.
SOURCES = [
    (RESULTS, ""),
    (ROOT / "results" / "pancake.json", "pancake"),
    (ROOT / "results" / "evidence.json", "evidence"),
    (ROOT / "results" / "profile.json", "profile"),
    (ROOT / "results" / "chain_diagnostics.json", "diag"),
    (ROOT / "results" / "map.json", "map"),
    (ROOT / "results" / "prior_sensitivity.json", "priorsens"),
    (ROOT / "results" / "theory_checks.json", "check"),
    (ROOT / "results" / "prior_width_summary.json", "width"),
    (ROOT / "results" / "growth_comparison.json", "growth"),
    (ROOT / "results" / "evidence_repeatability.json", "repeat"),
]

HEADER = (
    "% Auto-generated by scripts/gen_numbers.py from the files in SOURCES.\n"
    "% Do not edit by hand: `make tables` regenerates it and `make check`\n"
    "% fails if the committed file disagrees with the results.\n"
)


_DIGIT_LETTERS = "ZOTWFVXSEN"


def camel(path: str) -> str:
    """results key path -> a valid LaTeX macro name."""
    parts = re.split(r"[^A-Za-z0-9]+", path)
    out = "num"
    for p in parts:
        if not p:
            continue
        head = p[0].upper() + p[1:]
        # LaTeX command names cannot contain digits, so map each digit to a
        # distinct letter (Zero, One, Two, thWee, Four, fiVe, siX, Seven,
        # Eight, Nine); the mapping only has to be injective.
        out += re.sub(r"[0-9]", lambda m: _DIGIT_LETTERS[int(m.group())], head)
    return out


#: Default ``.4g`` is right for most quantities and badly wrong for a few.  A
#: log-evidence of -732.152 becomes "-732.2", and a chi-square of 1436.5179
#: becomes "1437"; both are quoted as *differences* between models, where the
#: interesting digits are the ones ``.4g`` throws away.  Keyed by the last
#: component of the results path.
FORMATS = {
    "logz": ".3f",
    "logz_err": ".3f",
    "ln_bayes_vs_lcdm": ".2f",
    "ln_bayes_err": ".2f",
    "chi2_min": ".4f",
    "chi2_spread": ".4f",
    "reference_chi2": ".4f",
    "reference_shortfall": ".4f",
    "chi2_at_zero": ".3f",
    "limit_95": ".4f",
    "max_delta_chi2": ".3g",
    "worst_identity_residual": ".2e",
    "bounded_suppression": ".1f",
    # An uncertainty carries two significant figures by convention; the
    # default four turned "68.38 +/- 0.30" into "68.38 +/- 0.2979".
    "err": ".2g",
    "err_hi": ".2g",
    "err_lo": ".2g",
    "acceptance": ".4f",
    "move_rate_early": ".4f",
    "move_rate_late": ".4f",
    "outside_prior_fraction": ".3f",
    "tau_max": ".0f",
    "median_ratio": ".2f",
    "ratio_p05": ".2g",
    "baseline": ".2f",
    "with_sh0es": ".2f",
    "ratio_p95": ".2f",
    "logz_spread": ".3f",
    "logz_reported_error": ".3f",
    "ratio_spread_to_reported": ".2f",
    "today": ".1e",
    "z_of_max": ".0f",
    "two_omega_r_today": ".2e",
    "length_in_tau": ".0f",
    "ln_bayes_full_prior": ".2f",
    "ln_bayes_span": ".2f",
    "seed_spread": ".2f",
    "odds_widest": ".2f",
    "odds_baseline": ".2f",
    "ln_bayes_range": ".2f",
    "ln_bayes_with_growth": ".2f",
    "ln_bayes_widest": ".2f",
    "ln_bayes_baseline": ".2f",
}


def fmt(value, spec: str | None = None) -> str:
    if isinstance(value, bool):
        return r"\text{true}" if value else r"\text{false}"
    if isinstance(value, int):
        return f"{value:,}".replace(",", r"{,}")
    if isinstance(value, float):
        text = f"{value:{spec}}" if spec else f"{value:.4g}"
        # A percent format emits a bare "%", which in LaTeX comments out the
        # rest of the line -- silently, and the macro then swallows whatever
        # follows it in the manuscript.
        return text.replace("%", r"\%")
    return str(value)


def _tail(prefix: str) -> str:
    """Longest registered FORMATS key that ``prefix`` ends with."""
    return next((k for k in sorted(FORMATS, key=len, reverse=True)
                 if prefix.endswith(k)), "")


def walk(node, prefix: str, out: dict[str, str],
         origin: dict[str, str] | None = None) -> None:
    """Flatten a results tree into macro name -> formatted value.

    ``origin`` maps each macro name to the results path that produced it, so a
    second path arriving at the same name can be reported instead of silently
    overwriting.  See :func:`collect`.
    """
    def put(name: str, value: str, path: str) -> None:
        if origin is not None and name in origin and origin[name] != path:
            raise SystemExit(
                f"macro name collision: \\{name} is produced by both "
                f"'{origin[name]}' (= {out[name]}) and '{path}' (= {value}). "
                f"camel() upper-cases each component, so keys differing only "
                f"in case collide. Rename one of the results keys.")
        out[name] = value
        if origin is not None:
            origin[name] = path

    if isinstance(node, dict):
        if "value" in node:
            put(camel(prefix), fmt(node["value"], node.get("fmt")), prefix)
            for extra in ("err", "err_lo", "err_hi"):
                if extra in node:
                    put(camel(f"{prefix}_{extra}"),
                        fmt(node[extra], node.get("fmt") or FORMATS.get(extra)),
                        f"{prefix}_{extra}")
            return
        for k, v in node.items():
            walk(v, f"{prefix}_{k}" if prefix else k, out, origin)
    elif isinstance(node, (int, float, str, bool)):
        put(camel(prefix),
            fmt(node, FORMATS.get(prefix.rsplit("_", 1)[-1])
                or FORMATS.get(_tail(prefix))), prefix)


def collect() -> dict[str, str]:
    """Macros from every registered results file, keyed by its prefix.

    Raises on a name collision.  ``camel`` upper-cases the first letter of each
    path component, so ``Omega_m0`` and ``omega_m0`` -- the density parameter
    and the physical density, differing by a factor of three -- both became
    ``numChainsLcdmBaselineDerivedOmegaMZ``, and whichever came last silently
    won. A wrong number in the manuscript is the worst failure this generator
    can have, so a collision now stops the build.
    """
    macros: dict[str, str] = {}
    origin: dict[str, str] = {}
    for path, prefix in SOURCES:
        if not path.exists():
            continue
        walk(json.loads(path.read_text()), prefix, macros, origin)
    return macros


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if not RESULTS.exists():
        OUT.write_text(HEADER + "% results/results.json not present yet\n")
        print(f"{RESULTS} missing; wrote an empty {OUT.name}")
        return 0
    macros = collect()
    body = "".join(f"\\newcommand{{\\{k}}}{{{v}\\xspace}}\n"
                   for k, v in sorted(macros.items()))
    OUT.write_text(HEADER + body)
    print(f"wrote {len(macros)} macros to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
